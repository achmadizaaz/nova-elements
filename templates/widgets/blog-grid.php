<?php

defined( 'ABSPATH' ) || exit;
?>
<div class="nova-widget nova-blog nova-blog--<?php echo esc_attr( $preset ); ?>">
	<?php if ( ! $posts ) : ?>
		<p class="nova-blog__empty"><?php esc_html_e( 'No posts match this selection.', 'nova-elements' ); ?></p>
	<?php else : ?>
		<div class="nova-blog__grid">
			<?php foreach ( $posts as $post_card ) : ?>
				<article class="nova-blog__card<?php echo $post_card['image'] ? ' nova-blog__card--has-image' : ''; ?>">
					<?php if ( $post_card['image'] ) : ?>
						<div class="nova-blog__media"><?php echo $post_card['image']; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress's thumbnail API. ?></div>
					<?php endif; ?>
					<div class="nova-blog__body">
						<?php if ( $post_card['term'] ) : ?>
							<span class="nova-blog__term"><?php echo esc_html( $post_card['term'] ); ?></span>
						<?php endif; ?>
						<<?php echo esc_html( $tag ); ?> class="nova-blog__title"><a href="<?php echo esc_url( $post_card['url'] ); ?>"><?php echo esc_html( $post_card['title'] ); ?></a></<?php echo esc_html( $tag ); ?>>
						<?php if ( $post_card['excerpt'] ) : ?>
							<p class="nova-blog__excerpt"><?php echo esc_html( $post_card['excerpt'] ); ?></p>
						<?php endif; ?>
						<?php if ( $post_card['date'] || $post_card['author'] ) : ?>
							<p class="nova-blog__meta">
								<?php if ( $post_card['date'] ) : ?>
									<time datetime="<?php echo esc_attr( $post_card['datetime'] ); ?>"><?php echo esc_html( $post_card['date'] ); ?></time>
								<?php endif; ?>
								<?php if ( $post_card['author'] ) : ?>
									<span><?php echo esc_html( $post_card['author'] ); ?></span>
								<?php endif; ?>
							</p>
						<?php endif; ?>
					</div>
				</article>
			<?php endforeach; ?>
		</div>
	<?php endif; ?>
	<?php if ( $total > 1 || $page > 1 ) : ?>
		<nav class="nova-blog__pagination" aria-label="<?php echo esc_attr( $label ); ?>">
			<?php if ( $page > 1 ) : ?>
				<a href="<?php echo esc_url( $page > $total ? remove_query_arg( $key ) : add_query_arg( $key, $page - 1 ) ); ?>">
					<?php echo $page > $total ? esc_html__( 'First page', 'nova-elements' ) : esc_html__( 'Previous', 'nova-elements' ); ?>
				</a>
			<?php endif; ?>
			<?php if ( $page <= $total ) : ?>
				<span><?php
					/* translators: 1: current page, 2: total pages. */
					printf( esc_html__( 'Page %1$s of %2$s', 'nova-elements' ), esc_html( number_format_i18n( $page ) ), esc_html( number_format_i18n( $total ) ) );
				?></span>
			<?php endif; ?>
			<?php if ( $page < $total ) : ?>
				<a href="<?php echo esc_url( add_query_arg( $key, $page + 1 ) ); ?>"><?php esc_html_e( 'Next', 'nova-elements' ); ?></a>
			<?php endif; ?>
		</nav>
	<?php endif; ?>
</div>
