<?php

defined( 'ABSPATH' ) || exit;

$classes = 'nova-widget nova-blog nova-blog--' . $preset;
if ( 'grid' !== $layout ) {
	$classes .= ' nova-blog--' . $layout;
}
$timeline = 'timeline' === $layout;
$grid_tag = $timeline ? 'ol' : 'div';
$lead = in_array( $layout, array( 'featured', 'magazine' ), true );
$support = $lead && count( $posts ) > 1;
if ( $support ) {
	$classes .= ' nova-blog--with-support';
}
$carousel = 'carousel' === $layout && count( $posts ) > 1;
if ( $carousel ) {
	$carousel_label = is_string( $settings['carousel_label'] ?? null ) ? trim( $settings['carousel_label'] ) : '';
	$carousel_label = $carousel_label ?: __( 'Latest articles', 'nova-elements' );
	$autoplay = 'yes' === ( $settings['carousel_autoplay'] ?? '' );
	$interval = $settings['carousel_interval'] ?? 6;
	$interval = is_numeric( $interval ) ? max( 4, min( 20, (int) $interval ) ) : 6;
}
?>
<div class="<?php echo esc_attr( $classes ); ?>">
	<?php if ( $error ) : ?>
		<p class="nova-blog__empty"><?php echo esc_html( $error->get_error_message() ); ?></p>
	<?php elseif ( ! $posts ) : ?>
		<p class="nova-blog__empty"><?php esc_html_e( 'No posts match this selection.', 'nova-elements' ); ?></p>
	<?php else : ?>
		<?php if ( $carousel ) : ?>
			<nova-post-carousel role="group" aria-roledescription="<?php esc_attr_e( 'carousel', 'nova-elements' ); ?>" aria-label="<?php echo esc_attr( $carousel_label ); ?>" data-interval="<?php echo esc_attr( $autoplay ? $interval * 1000 : 0 ); ?>">
				<?php require __DIR__ . '/blog-carousel-controls.php'; ?>
		<?php endif; ?>
		<<?php echo esc_html( $grid_tag ); ?> class="nova-blog__grid"<?php if ( $timeline ) : ?> role="list"<?php endif; ?><?php if ( $carousel ) : ?> tabindex="0" role="group" aria-label="<?php esc_attr_e( 'Scroll through articles', 'nova-elements' ); ?>"<?php endif; ?>>
			<?php foreach ( $posts as $index => $post_card ) : ?>
				<?php if ( $support && 1 === $index ) : ?>
					<div class="nova-blog__support">
				<?php endif; ?>
				<?php if ( $timeline ) : ?>
					<li class="nova-blog__entry">
				<?php endif; ?>
				<article class="nova-blog__card<?php echo $lead && 0 === $index ? ' nova-blog__card--lead' : ''; ?><?php echo $post_card['image'] ? ' nova-blog__card--has-image' : ''; ?>">
					<?php if ( $timeline && $post_card['date'] ) : ?>
						<time class="nova-blog__date" datetime="<?php echo esc_attr( $post_card['datetime'] ); ?>"><?php echo esc_html( $post_card['date'] ); ?></time>
					<?php endif; ?>
					<?php if ( $post_card['image'] ) : ?>
						<div class="nova-blog__media"><?php echo $post_card['image']; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress's thumbnail API. ?></div>
					<?php endif; ?>
					<div class="nova-blog__body">
						<?php if ( $post_card['term'] ) : ?>
							<span class="nova-blog__term"><?php echo esc_html( $post_card['term'] ); ?></span>
						<?php endif; ?>
						<<?php echo esc_html( $tag ); ?> class="nova-blog__title"><a href="<?php echo esc_url( $post_card['url'] ); ?>"><?php echo esc_html( $post_card['title'] ); ?></a></<?php echo esc_html( $tag ); ?>>
						<?php if ( $post_card['excerpt'] ) : ?>
							<p class="nova-blog__excerpt"><?php echo esc_html( $post_card['excerpt'] ); ?></p>
						<?php endif; ?>
						<?php if ( ( ! $timeline && $post_card['date'] ) || $post_card['author'] ) : ?>
							<p class="nova-blog__meta">
								<?php if ( ! $timeline && $post_card['date'] ) : ?>
									<time datetime="<?php echo esc_attr( $post_card['datetime'] ); ?>"><?php echo esc_html( $post_card['date'] ); ?></time>
								<?php endif; ?>
								<?php if ( $post_card['author'] ) : ?>
									<span><?php echo esc_html( $post_card['author'] ); ?></span>
								<?php endif; ?>
							</p>
						<?php endif; ?>
					</div>
				</article>
				<?php if ( $timeline ) : ?>
					</li>
				<?php endif; ?>
			<?php endforeach; ?>
			<?php if ( $support ) : ?>
				</div>
			<?php endif; ?>
		</<?php echo esc_html( $grid_tag ); ?>>
		<?php if ( $carousel ) : ?>
			</nova-post-carousel>
		<?php endif; ?>
	<?php endif; ?>
	<?php if ( $total > 1 || $page > 1 ) : ?>
		<nav class="nova-blog__pagination" aria-label="<?php echo esc_attr( $label ); ?>">
			<?php if ( $page > 1 ) : ?>
				<a href="<?php echo esc_url( $page > $total ? remove_query_arg( $key ) : add_query_arg( $key, $page - 1 ) ); ?>">
					<?php echo $page > $total ? esc_html__( 'First page', 'nova-elements' ) : esc_html__( 'Previous', 'nova-elements' ); ?>
				</a>
			<?php endif; ?>
			<?php if ( $numbered && $page <= $total ) : ?>
				<?php
				$numbers = array_unique( array_merge( array( 1 ), range( max( 1, $page - 2 ), min( $total, $page + 2 ) ), array( $total ) ) );
				$previous = 0;
				foreach ( $numbers as $number ) :
					if ( $previous && $number > $previous + 1 ) :
						?><span aria-hidden="true">…</span><?php
					endif;
					$previous = $number;
					/* translators: %s: page number. */
					$page_label = sprintf( __( 'Page %s', 'nova-elements' ), number_format_i18n( $number ) );
					if ( $number === $page ) :
						?><span aria-current="page" aria-label="<?php echo esc_attr( $page_label ); ?>"><?php echo esc_html( number_format_i18n( $number ) ); ?></span><?php
					else :
						?><a href="<?php echo esc_url( 1 === $number ? remove_query_arg( $key ) : add_query_arg( $key, $number ) ); ?>" aria-label="<?php echo esc_attr( $page_label ); ?>"><?php echo esc_html( number_format_i18n( $number ) ); ?></a><?php
					endif;
				endforeach;
				?>
			<?php elseif ( $page <= $total ) : ?>
				<span><?php
					/* translators: 1: current page, 2: total pages. */
					printf( esc_html__( 'Page %1$s of %2$s', 'nova-elements' ), esc_html( number_format_i18n( $page ) ), esc_html( number_format_i18n( $total ) ) );
				?></span>
			<?php endif; ?>
			<?php if ( $page < $total ) : ?>
				<a href="<?php echo esc_url( add_query_arg( $key, $page + 1 ) ); ?>"><?php esc_html_e( 'Next', 'nova-elements' ); ?></a>
			<?php endif; ?>
		</nav>
	<?php endif; ?>
</div>
