<?php

defined( 'ABSPATH' ) || exit;

$carousel = in_array( $kind, array( 'carousel', 'logos' ), true );
?>
<nova-media class="nova-widget nova-media nova-media--<?php echo esc_attr( $kind ); ?> nova-media--<?php echo esc_attr( $preset ); ?>" role="region" aria-label="<?php echo esc_attr( $label ); ?>">
	<?php if ( $categories ) : ?>
		<div class="nova-media__filters" role="group" aria-label="<?php esc_attr_e( 'Filter images', 'nova-elements' ); ?>" hidden>
			<button type="button" aria-pressed="true" data-media-filter=""><?php esc_html_e( 'All images', 'nova-elements' ); ?></button>
			<?php foreach ( $categories as $category ) : ?>
				<button type="button" aria-pressed="false" data-media-filter="<?php echo esc_attr( $category ); ?>"><?php echo esc_html( $category ); ?></button>
			<?php endforeach; ?>
		</div>
	<?php endif; ?>
	<?php if ( $carousel && count( $items ) > 1 ) : ?>
		<div class="nova-media__navigation" hidden>
			<button type="button" data-media-step="-1"><?php esc_html_e( 'Previous', 'nova-elements' ); ?></button>
			<button type="button" data-media-step="1"><?php esc_html_e( 'Next', 'nova-elements' ); ?></button>
		</div>
	<?php endif; ?>
	<div class="nova-media__items"<?php if ( $carousel ) : ?> tabindex="0" role="group" aria-label="<?php esc_attr_e( 'Slides', 'nova-elements' ); ?>"<?php endif; ?>>
		<?php foreach ( $items as $index => $item ) : ?>
			<?php
			$name = $item['title'] ?: ( $item['alt'] ?: ( $item['video'] ? __( 'Video', 'nova-elements' ) : __( 'Image', 'nova-elements' ) ) );
			$action = $item['video']['link'] ?? ( $lightbox ? $item['full'] : '' );
			$type = $item['video']['type'] ?? 'image';
			$source = $item['video']['url'] ?? $item['full'];
			if ( 'accordion' === $kind ) :
				?>
				<details class="nova-media__item"<?php echo 0 === $index ? ' open' : ''; ?>>
					<summary><?php echo esc_html( $name ); ?></summary>
				<?php endif; ?>
				<figure class="<?php echo 'accordion' === $kind ? 'nova-media__figure' : 'nova-media__item'; ?>" data-media-category="<?php echo esc_attr( $item['category'] ); ?>">
					<div class="nova-media__frame">
						<?php if ( $action ) : ?>
							<a class="nova-media__open" href="<?php echo esc_url( $action ); ?>" data-media-type="<?php echo esc_attr( $type ); ?>" data-media-source="<?php echo esc_url( $source ); ?>" data-media-title="<?php echo esc_attr( $name ); ?>"<?php echo $item['video'] ? ' rel="noreferrer"' : ''; ?><?php if ( $item['track'] ) : ?> data-media-track="<?php echo esc_url( $item['track'] ); ?>" data-media-language="<?php echo esc_attr( $item['language'] ); ?>"<?php endif; ?>>
						<?php endif; ?>
						<?php echo $item['image']; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by the media helper. ?>
						<?php if ( $action ) : ?>
							<span class="nova-media__action"><?php echo esc_html( $item['video'] ? __( 'Play video', 'nova-elements' ) : __( 'Enlarge image', 'nova-elements' ) ); ?><span class="nova-media__visually-hidden"><?php echo esc_html( ' ' . $name ); ?></span></span>
							</a>
						<?php endif; ?>
					</div>
					<?php if ( ( 'accordion' !== $kind && '' !== $item['title'] ) || '' !== $item['caption'] ) : ?>
						<figcaption class="nova-media__caption">
							<?php if ( 'accordion' !== $kind && '' !== $item['title'] ) : ?><strong><?php echo esc_html( $item['title'] ); ?></strong><?php endif; ?>
							<?php if ( '' !== $item['caption'] ) : ?><p><?php echo esc_html( $item['caption'] ); ?></p><?php endif; ?>
						</figcaption>
					<?php endif; ?>
				</figure>
			<?php if ( 'accordion' === $kind ) : ?></details><?php endif; ?>
		<?php endforeach; ?>
	</div>
	<dialog class="nova-media__dialog" data-close-label="<?php esc_attr_e( 'Close media', 'nova-elements' ); ?>"></dialog>
</nova-media>
