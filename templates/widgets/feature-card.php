<?php

defined( 'ABSPATH' ) || exit;

$classes = 'nova-widget nova-feature nova-feature--' . $preset;
if ( 'feature' !== $kind ) {
	$classes .= ' nova-feature--' . $kind;
}
if ( '' !== $effect ) {
	$classes .= ' nova-feature--effect-' . $effect;
}
if ( $items ) {
	$classes .= ' nova-feature--has-items';
}
if ( '' !== $image || '' !== $icon || '' !== $initials ) {
	$classes .= ' nova-feature--has-media';
	if ( '' !== $position ) {
		$classes .= ' nova-feature--media-' . $position;
	}
}
?>
<div class="nova-feature-frame">
	<article class="<?php echo esc_attr( $classes ); ?>">
		<?php if ( '' !== $image && '' !== $caption ) : ?>
			<figure class="nova-feature__image nova-feature__figure">
				<div class="nova-feature__visual"><?php echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by the media helper. ?></div>
				<figcaption class="nova-feature__detail"><?php echo esc_html( $caption ); ?></figcaption>
			</figure>
		<?php elseif ( '' !== $image ) : ?>
			<div class="nova-feature__image"><?php echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by the media helper. ?></div>
		<?php elseif ( '' !== $initials ) : ?>
			<div class="nova-feature__image nova-feature__image--initials" aria-hidden="true"><?php echo esc_html( $initials ); ?></div>
		<?php elseif ( '' !== $icon ) : ?>
			<div class="nova-feature__icon" aria-hidden="true"><?php echo $icon; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Rendered by Elementor's icon API. ?></div>
		<?php endif; ?>
		<div class="nova-feature__body">
			<?php if ( '' !== $eyebrow ) : ?>
				<p class="nova-feature__eyebrow"><?php echo esc_html( $eyebrow ); ?></p>
			<?php endif; ?>
			<?php if ( '' !== $title ) : ?>
				<<?php echo esc_html( $tag ); ?> class="nova-feature__title"><?php echo esc_html( $title ); ?></<?php echo esc_html( $tag ); ?>>
			<?php endif; ?>
			<?php if ( '' !== $description ) : ?>
				<p class="nova-feature__description"><?php echo esc_html( $description ); ?></p>
			<?php endif; ?>
			<?php if ( '' !== $note ) : ?>
				<p class="nova-feature__detail nova-feature__note"><?php echo esc_html( $note ); ?></p>
			<?php endif; ?>
			<?php if ( '' !== $price ) : ?>
				<?php
				$previous = $this->text_value( $settings['price_previous'] ?? null );
				$period = $this->text_value( $settings['price_period'] ?? null );
				?>
				<p class="nova-feature__price">
					<?php if ( '' !== $previous ) : ?>
						<span class="nova-feature__visually-hidden"><?php esc_html_e( 'Previous price', 'nova-elements' ); ?></span>
						<s class="nova-feature__price-previous"><?php echo esc_html( $previous ); ?></s>
						<span class="nova-feature__visually-hidden"><?php esc_html_e( 'Current price', 'nova-elements' ); ?></span>
					<?php endif; ?>
					<span class="nova-feature__price-current"><?php echo esc_html( $price ); ?></span>
					<?php if ( '' !== $period ) : ?>
						<span class="nova-feature__price-period"><?php echo esc_html( $period ); ?></span>
					<?php endif; ?>
				</p>
			<?php endif; ?>
			<?php if ( $points ) : ?>
				<ul class="nova-feature__detail nova-feature__points" role="list">
					<?php foreach ( $points as $point ) : ?>
						<li><?php echo esc_html( $point ); ?></li>
					<?php endforeach; ?>
				</ul>
			<?php endif; ?>
			<?php if ( '' !== $back_title || '' !== $back_description ) : ?>
				<?php $flip_label = $this->text_value( $settings['flip_label'] ?? null ); ?>
				<details class="nova-feature__flip">
					<summary class="nova-feature__flip-toggle">
						<?php echo esc_html( '' !== $flip_label ? $flip_label : __( 'View details', 'nova-elements' ) ); ?>
						<?php if ( '' !== $title ) : ?>
							<span class="nova-feature__visually-hidden"><?php echo esc_html( $title ); ?></span>
						<?php endif; ?>
					</summary>
					<div class="nova-feature__flip-back nova-feature__detail">
						<?php if ( '' !== $back_title ) : ?>
							<p><strong><?php echo esc_html( $back_title ); ?></strong></p>
						<?php endif; ?>
						<?php if ( '' !== $back_description ) : ?>
							<p><?php echo esc_html( $back_description ); ?></p>
						<?php endif; ?>
					</div>
				</details>
			<?php endif; ?>
			<?php if ( $linked ) : ?>
				<a class="nova-feature__link" <?php $this->print_render_attribute_string( 'feature_link' ); ?>>
					<span><?php echo esc_html( $cta ); ?></span><span class="nova-feature__arrow" aria-hidden="true">&rarr;</span>
				</a>
			<?php endif; ?>
		</div>
		<?php if ( $items ) : ?>
			<ul class="nova-feature__items nova-feature__detail" role="list">
				<?php foreach ( $items as $item ) : ?>
					<li class="nova-feature__item">
						<?php if ( '' !== $item['title'] ) : ?>
							<strong><?php echo esc_html( $item['title'] ); ?></strong>
						<?php endif; ?>
						<?php if ( '' !== $item['description'] ) : ?>
							<p><?php echo esc_html( $item['description'] ); ?></p>
						<?php endif; ?>
					</li>
				<?php endforeach; ?>
			</ul>
		<?php endif; ?>
	</article>
</div>
